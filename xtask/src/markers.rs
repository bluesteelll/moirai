//! AI-attribution markers: the rules of `.githooks/commit-msg` (WP-03), applied by `xtask gate` to every commit of
//! `master..HEAD` (WP-02), by `xtask hook pr-body` to a pull request's title and body, and by `xtask ci commits` to
//! every commit of a pull request or a push (WP-04). docs/m0/PLAN.md §3.2 item 7; AGENTS.md "Git"; authors.md §5
//! item 4 (the three layers).
//!
//! This is a byte-for-byte port of the hook's POSIX awk program, which runs in the C locale: text is compared after
//! ASCII lower-casing, and "word" characters are `[a-z0-9_]`. Rules, case-insensitive:
//! 1. any `Co-authored-by` trailer, whoever it names;
//! 2. "Generated with" or "Generated by" followed on the same line by an AI tool name;
//! 3. `noreply@anthropic.com` and other addresses at AI vendors, and the GitHub noreply addresses of AI agents;
//! 4. Claude, Anthropic, Codex, OpenAI or Copilot in a trailer or an attribution line;
//! 5. the robot emoji U+1F916.
//!
//! The hook and this module are tested with the same cases (`.githooks/test-hooks.sh` and the tests below).

/// One refused line.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Refusal {
    pub rule: u8,
    pub what: &'static str,
    pub place: String,
    pub text: String,
}

impl std::fmt::Display for Refusal {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "rule {}, {}: {}: {}",
            self.rule, self.what, self.place, self.text
        )
    }
}

